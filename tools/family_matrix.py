#!/usr/bin/env python3
"""docs/FAMILIES.md: what the registers say about each model family, generated, never hand-kept.

The knowledge of which family does what is spread across the capability contract, the claims register and several dated
documents (docs/support_matrix.md, docs/ARCHITECTURE_SUPPORT.md, ...), and none of them is a cross-capability view.
This script builds that view from the two machine-readable registers, so a family that gains a claim or a supported
path shows it without a hand edit:

* docs/capabilities.json: each capability's ``model_families``, and ``training_support.by_model_type`` (one status per
  training path per family, with the claim ids behind it);
* docs/claims.json: every claim, mapped to a family by the Hugging Face repository ids its ``model`` field names
  (:data:`REPO_FAMILY`). A claim whose ``model`` names no mapped repository is listed at the end, never guessed.

The dated documents stay as their evidence bundles; this page indexes the registers and supersedes none of them.

    python tools/family_matrix.py          # rewrite docs/FAMILIES.md
    python tools/family_matrix.py --check  # exit 1 when docs/FAMILIES.md is not what the registers say (CI)

Standard library only, no network, and no clock: the same registers always give the same page.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAPABILITIES = ROOT / "docs" / "capabilities.json"
CLAIMS = ROOT / "docs" / "claims.json"
OUT = ROOT / "docs" / "FAMILIES.md"

#: Hugging Face repository-id prefix -> transformers ``model_type``. A claim counts for every family its ``model``
#: names; a repository that matches no prefix leaves the claim unmapped (listed at the end of the page).
REPO_FAMILY = (
    ("Qwen/Qwen3-30B-A3B", "qwen3_moe"),
    ("Qwen/Qwen3-235B-A22B", "qwen3_moe"),
    ("Qwen/Qwen3.6-35B-A3B", "qwen3_5_moe"),
    ("mistralai/Mixtral-", "mixtral"),
    ("ibm-granite/granite-3.", "granitemoe"),
    ("ibm-granite/granite-4.0-h", "granitemoehybrid"),
    ("google/gemma-4-", "gemma4_text"),
    ("openai/gpt-oss-", "gpt_oss"),
    ("allenai/OLMoE-", "olmoe"),
    ("LiquidAI/LFM2-", "lfm2_moe"),
    ("baidu/ERNIE-4.5-", "ernie4_5_moe"),
    ("nvidia/NVIDIA-Nemotron-", "nemotron_h"),
)
#: statuses that count as current evidence; ``superseded``, ``retired`` and ``open`` rows are not
PUBLIC_STATUSES = ("verified", "measured")
PRIVATE_STATUSES = ("measured-private",)
#: training statuses that credit a family with nothing, so they need no claim id behind them
NO_CREDIT = ("not_tested", "n/a", "refused")
NO_CLAIM = "no claim id"
REPO_RE = re.compile(r"(?<![\w./-])([A-Za-z0-9][\w.-]*/[A-Za-z0-9][\w.-]*)")


def families_of(model) -> list:
    """The families a claim's ``model`` names, in the order it names them, without repeats."""
    out = []
    for repo in REPO_RE.findall(str(model or "")):
        fam = next((f for prefix, f in REPO_FAMILY if repo.startswith(prefix)), None)
        if fam and fam not in out:
            out.append(fam)
    return out


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(capabilities: dict, claims: dict) -> str:
    caps = capabilities["capabilities"]
    rows = claims["claims"]

    order: list = []                                   # families in the order the registers first name them

    def seen(fam):
        if fam not in order:
            order.append(fam)

    trained = [c for c in caps if c.get("training_support")]
    for c in trained:
        for fam in c["training_support"]["by_model_type"]:
            seen(fam)
    for c in caps:
        for fam in c.get("model_families") or ():
            seen(fam)
    by_family: dict = {}
    unmapped: dict = {}
    for r in rows:
        fams = families_of(r.get("model"))
        if not fams:
            key = "(no `model`)" if r.get("model") in (None, "") else str(r.get("model"))
            unmapped[key] = unmapped.get(key, 0) + 1
        for fam in fams:
            seen(fam)
            by_family.setdefault(fam, []).append(r)

    out = ["# Model families: what the registers say", "",
           "<!-- Generated by tools/family_matrix.py from docs/capabilities.json and docs/claims.json. Do not edit by "
           "hand: change a register, then run `python tools/family_matrix.py`. CI runs it with --check. -->", "",
           "One view per model family (transformers `model_type`) of what the project's two registers record. A cell "
           "changes when a register changes, never by hand. The dated documents "
           "([support matrix](support_matrix.md), [architecture support](ARCHITECTURE_SUPPORT.md)) keep their "
           "evidence; this page indexes the registers and supersedes neither.", ""]

    for c in trained:
        ts = c["training_support"]
        paths: list = []
        for per in ts["by_model_type"].values():
            for p in per:
                if p not in paths:
                    paths.append(p)
        out += [f"## Training paths: `{c['id']}`", "",
                "From `docs/capabilities.json` (`training_support.by_model_type`; "
                + (f"the headline path is `{ts['headline_path']}`" if ts.get("headline_path") else "no headline path")
                + "). Each cell is the path's status and, in brackets, how many claim ids back it. A status that "
                f"credits the family (anything but {', '.join(f'`{s}`' for s in NO_CREDIT)}) with no claim id behind "
                f"it reads `status, {NO_CLAIM}`.", "",
                "| family | " + " | ".join(f"`{p}`" for p in paths) + " |",
                "|---|" + "---|" * len(paths)]
        for fam, per in ts["by_model_type"].items():
            cells = []
            for p in paths:
                e = per.get(p)
                if not isinstance(e, dict):
                    cells.append("-" if e is None else _cell(e))
                    continue
                n = len(e.get("claim_ids") or ())
                status = str(e.get("status", "?"))
                if n:
                    cells.append(_cell(status) + f" ({n})")
                else:
                    cells.append(_cell(status) + ("" if status in NO_CREDIT else f", {NO_CLAIM}"))
            out.append(f"| `{fam}` | " + " | ".join(cells) + " |")
        out.append("")

    out += ["## Capabilities that list each family", "",
            "From `docs/capabilities.json` (each capability's `model_families`; its status is in the header). "
            "`listed (N)`: N current claims among the capability's own `claim_ids` name the family's model "
            f"(mapped as in the claims table below). `listed, {NO_CLAIM}`: the capability lists the family, but none "
            "of its current claim ids names it.", "",
            "| family | " + " | ".join(f"`{c['id']}` ({_cell(c.get('status'))})" for c in caps) + " |",
            "|---|" + "---|" * len(caps)]
    current = {r.get("id"): r for r in rows if r.get("status") in PUBLIC_STATUSES + PRIVATE_STATUSES}
    listed = [{str(f) for f in (c.get("model_families") or ())} for c in caps]
    backing = []                                       # per capability: family -> current claim ids that name it
    for c in caps:
        per: dict = {}
        for cid in c.get("claim_ids") or ():
            if cid in current:
                for fam in families_of(current[cid].get("model")):
                    per[fam] = per.get(fam, 0) + 1
        backing.append(per)
    for fam in order:
        if not any(fam in s for s in listed):
            continue
        cells = []
        for s, per in zip(listed, backing):
            if fam not in s:
                cells.append("-")
            else:
                cells.append(f"listed ({per[fam]})" if per.get(fam) else f"listed, {NO_CLAIM}")
        out.append(f"| `{fam}` | " + " | ".join(cells) + " |")
    out.append("")

    areas = sorted({str(r.get("area")) for r in rows if r.get("area")})
    out += ["## Claims on record", "",
            "From `docs/claims.json`. Each cell counts the current claims for that family and area: "
            f"{' or '.join(PUBLIC_STATUSES)} (a public receipt), then `+N private` for {', '.join(PRIVATE_STATUSES)} rows (a receipt "
            "this repository cannot show). Superseded, retired and open rows are not counted. The last column is the "
            "newest `measured_on` among the counted rows. A claim that names several families counts for each.", "",
            "| family | " + " | ".join(f"`{a}`" for a in areas) + " | newest |",
            "|---|" + "---|" * (len(areas) + 1)]
    for fam in order:
        rs = by_family.get(fam, [])
        live = [r for r in rs if r.get("status") in PUBLIC_STATUSES + PRIVATE_STATUSES]
        if not live:
            continue
        cells = []
        for a in areas:
            pub = sum(1 for r in live if r.get("area") == a and r.get("status") in PUBLIC_STATUSES)
            prv = sum(1 for r in live if r.get("area") == a and r.get("status") in PRIVATE_STATUSES)
            cells.append(("-" if not pub and not prv else str(pub)) + (f" +{prv} private" if prv else ""))
        newest = max((str(r.get("measured_on")) for r in live if r.get("measured_on")), default="-")
        out.append(f"| `{fam}` | " + " | ".join(cells) + f" | {newest} |")
    out.append("")

    out += ["## Claims not mapped to a family", "",
            "Their `model` field names no repository in `tools/family_matrix.py`'s `REPO_FAMILY` (synthetic "
            "checkpoints, several families at once in prose, or a family not mapped yet). Map a repository there, "
            "never here.", ""]
    if unmapped:
        out += ["| `model` | claims |", "|---|---|"]
        for model, n in sorted(unmapped.items()):
            out.append(f"| {_cell(model)} | {n} |")
    else:
        out.append("None.")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when docs/FAMILIES.md is not current")
    args = ap.parse_args(argv)
    page = render(json.loads(CAPABILITIES.read_text(encoding="utf-8")), json.loads(CLAIMS.read_text(encoding="utf-8")))
    want = page.encode("utf-8")                        # bytes, so the generator owns the line endings (LF)
    if args.check:
        cur = OUT.read_bytes() if OUT.exists() else None
        if cur != want:
            print(f"FAIL: {OUT.relative_to(ROOT)} is not what the registers say; run `python tools/family_matrix.py` "
                  "and commit the result", file=sys.stderr)
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_bytes(want)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
