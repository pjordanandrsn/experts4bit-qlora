#!/usr/bin/env python3
"""docs/COMPARATORS.md: which comparator versions the current claims were measured against, generated from
docs/claims.json, never hand-kept.

Every public comparison carries the comparator's version and date. This page lists, per comparator (vLLM, SGLang,
Unsloth, axolotl), each version the current claims name and how many claims name it. It also lists the claims that
name a comparator with no version anywhere the register keeps one. A weekly check elsewhere (the public-surface
lockstep run) compares the newest version on record here against PyPI and REPORTS a newer release. It never edits a
claim and never flips a default.

A version is read only from a claim's ``id``, ``claim``, ``conditions`` and ``hardware`` (``notes`` carry unlicensed
arms), and only in the comparator's own release shape (:data:`COMPARATORS`), so a number that merely follows a
comparator's name, such as a loss value, is never read as its version. A current claim is ``verified``, ``measured``
or ``measured-private``; superseded, retired and open rows are not counted.

    python tools/comparator_table.py          # rewrite docs/COMPARATORS.md
    python tools/comparator_table.py --check  # exit 1 when docs/COMPARATORS.md is not what the register says (CI)

Standard library only, no network, and no clock.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLAIMS = ROOT / "docs" / "claims.json"
OUT = ROOT / "docs" / "COMPARATORS.md"

#: comparator -> (its PyPI name, the name as written in the register, its release-version shape: three dotted parts, so
#: a ratio or a loss such as "1.0043x" is never a version, and a 1.x release still is)
COMPARATORS = {
    "vLLM": ("vllm", r"vLLM", r"\d+\.\d+\.\d+(?:\.post\d+)?"),
    "SGLang": ("sglang", r"SGLang", r"\d+\.\d+\.\d+(?:\.post\d+)?"),
    "Unsloth": ("unsloth", r"Unsloth", r"20\d\d\.\d{1,2}\.\d{1,2}"),
    "axolotl": ("axolotl", r"axolotl", r"\d+\.\d+\.\d+"),
}
CURRENT_STATUSES = ("verified", "measured", "measured-private")
FIELDS = ("id", "claim", "conditions", "hardware")
_VERSION = {k: re.compile(r"\b" + name + r"\b[ =@v-]{0,3}(" + ver + r")\b", re.I) for k, (_p, name, ver) in COMPARATORS.items()}
_NAME = {k: re.compile(r"\b" + name + r"\b", re.I) for k, (_p, name, _v) in COMPARATORS.items()}


def _key(version: str) -> tuple:
    return tuple(int(p) if p.isdigit() else -1 for p in re.split(r"[.]", version.replace("post", "")))


def read(claims: dict) -> dict:
    """``{comparator: {"versions": {version: [claim, ...]}, "bare": [claim, ...]}}`` over the current claims."""
    out = {k: {"versions": {}, "bare": []} for k in COMPARATORS}
    for c in claims["claims"]:
        if c.get("status") not in CURRENT_STATUSES:
            continue
        text = " ".join(str(c.get(f) or "") for f in FIELDS)
        for k in COMPARATORS:
            found = sorted(set(_VERSION[k].findall(text)), key=_key)
            for v in found:
                out[k]["versions"].setdefault(v, []).append(c)
            if not found and _NAME[k].search(text):
                out[k]["bare"].append(c)
    return out


def newest_on_record(claims: dict) -> dict:
    """``{pypi name: the newest version any current claim names}`` (comparators no claim names are absent)."""
    got = read(claims)
    return {COMPARATORS[k][0]: max(r["versions"], key=_key) for k, r in got.items() if r["versions"]}


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(claims: dict) -> str:
    got = read(claims)
    out = ["# Comparator versions on record", "",
           "<!-- Generated by tools/comparator_table.py from docs/claims.json. Do not edit by hand: change the "
           "register, then run `python tools/comparator_table.py`. CI runs it with --check. -->", "",
           "Which version of each comparator the current claims in `docs/claims.json` were measured against. A version "
           "is read from a claim's id, sentence, conditions and hardware, in the comparator's release shape. "
           "Superseded, retired and open rows are not counted. A comparator with a newer PyPI release than the newest "
           "version here is reported weekly by the public-surface check; that report never edits a claim.", "",
           "| comparator | PyPI | version | current claims | areas | newest `measured_on` |",
           "|---|---|---|---|---|---|"]
    for k, (pypi, _n, _v) in COMPARATORS.items():
        versions = got[k]["versions"]
        if not versions:
            out.append(f"| {k} | `{pypi}` | none on record | 0 | - | - |")
            continue
        for v in sorted(versions, key=_key, reverse=True):
            rows = versions[v]
            areas = ", ".join(sorted({str(r.get("area")) for r in rows if r.get("area")})) or "-"
            newest = max((str(r.get("measured_on")) for r in rows if r.get("measured_on")), default="-")
            out.append(f"| {k} | `{pypi}` | {v} | {len(rows)} | {areas} | {newest} |")
    out += ["", "## Claims that name a comparator without a version", "",
            "These name the comparator in their id, sentence, conditions or hardware, but give no version there in its "
            "release shape. A public number carries its comparator's version and date, so each is a row to fix in the "
            "register (the version may be in `notes`, which this page does not read).", ""]
    bare = [(k, c) for k in COMPARATORS for c in got[k]["bare"]]
    if bare:
        out += ["| comparator | claim | `measured_on` |", "|---|---|---|"]
        for k, c in sorted(bare, key=lambda kc: (kc[0], str(kc[1].get("id")))):
            out.append(f"| {k} | `{_cell(c.get('id'))}` | {_cell(c.get('measured_on') or '-')} |")
    else:
        out.append("None.")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when docs/COMPARATORS.md is not current")
    ap.add_argument("--json", action="store_true", help="print {pypi name: newest version on record} and exit")
    args = ap.parse_args(argv)
    claims = json.loads(CLAIMS.read_text(encoding="utf-8"))
    if args.json:
        print(json.dumps(newest_on_record(claims), sort_keys=True))
        return 0
    page = render(claims)
    if args.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if cur != page:
            print(f"FAIL: {OUT.relative_to(ROOT)} is not what the register says; run `python tools/comparator_table.py` "
                  "and commit the result", file=sys.stderr)
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(page, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
